package com.voxelgame.engine;

/** Kiểu khí hậu quyết định địa tầng và thảm thực vật của từng cột. */
public enum BiomeType {
    /** Đồng bằng ôn hòa, có sồi, cỏ và hoa. */
    PLAINS,
    /** Vùng nóng khô, có cồn cát, xương rồng và ốc đảo. */
    DESERT,
    /** Đồng bằng lạnh, có tuyết, hồ đóng băng và cây vân sam. */
    SNOWY_PLAINS
}
